// Native-project mechanics for the nativ CLI: where the Capacitor projects live,
// the colour-driven splash/icon patchers, the SPA build, and the `cap` wrappers.
// Extracted from bin/nativ.mjs so the entry file stays a thin dispatcher. Every
// long-running command streams through the captured `exec` (see exec.mjs) so its
// output can be rendered as calm steps instead of a raw log dump.
import { spawnSync } from "node:child_process"
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { createRequire } from "node:module"
import { homedir } from "node:os"
import path from "node:path"
import { exec } from "./exec.mjs"

/** The hidden generated dir (mirrors src/vite/nativ-dir.ts — kept in sync by hand). */
export const NATIV_DIR = ".nativ"
/** Absolute path to a platform's native project, now under `.nativ/`. */
export const nativeDir = (appRoot, platform) =>
  path.join(appRoot, NATIV_DIR, platform)

/**
 * Delete a platform project's transient build caches. Xcode bakes the project's
 * absolute path into DerivedData's precompiled modules (PCH/ModuleCache), so a
 * relocated project must not reuse them — everything here is regenerated by the next
 * `cap sync` / build. Safe to call on the current or a legacy location.
 */
export function purgeBuildArtifacts(dir, platform) {
  const rm = (...parts) =>
    rmSync(path.join(dir, ...parts), { recursive: true, force: true })
  if (platform === "ios") {
    rm("DerivedData")
    rm("build")
    rm("App", "build")
  } else {
    rm(".gradle")
    rm("build")
    rm("app", "build")
    rm("capacitor-cordova-android-plugins", "build")
  }
}

/** The SPA build output the Capacitor WebView loads. */
export const CAP_WEB_DIR = "dist/client"

/** Path to a local `node_modules/.bin/<name>`, or null. */
export function localBin(appRoot, name) {
  const p = path.join(appRoot, "node_modules", ".bin", name)
  return existsSync(p) ? p : null
}

/** Resolve `cap` (Capacitor CLI); prefer the local install, fall back to npx. */
export function capCmd(appRoot) {
  const local = localBin(appRoot, "cap")
  return local
    ? { cmd: local, pre: [] }
    : { cmd: "npx", pre: ["--yes", "@capacitor/cli"] }
}

/** Run a captured command; each raw line goes to `report`. Throws on failure. */
function run(cmd, args, { cwd, env, report } = {}) {
  return exec(cmd, args, { cwd, env, onLine: (l) => report?.(l) })
}

