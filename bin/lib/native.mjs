/**
 * Brand the launcher icons + splash. Splash patches are synchronous file writes; the
 * launcher icon is generated via @capacitor/assets. Returns any non-fatal warnings
 * (missing source art / generator) so the caller can surface them after the run.
 */
export async function generateAssets(
  appRoot,
  config,
  platforms,
  { report } = {},
) {
  const warnings = []
  const icon = resolveIconPlan(config)
  const mask = resolveSplashMask(config)
  if (platforms.includes("android"))
    patchAndroidSplash(appRoot, mask, config.appId)
  if (platforms.includes("ios")) patchIosTheme(appRoot, mask)

  const dir = path.resolve(appRoot, icon.dir)
  const logo = path.join(dir, "logo.png")
  if (!existsSync(logo)) {
    warnings.push(
      `no ${icon.dir}/logo.png — kept existing launcher icons.`,
    )
    return { warnings }
  }
  const bin = localBin(appRoot, "capacitor-assets")
  if (!bin) {
    warnings.push(
      "@capacitor/assets not installed — kept existing launcher icons (add: pnpm add -D @capacitor/assets).",
    )
    return { warnings }
  }
  report?.("branding launcher icon from ./assets/logo.png")
  const args = [
    "generate",
    "--assetPath",
    icon.dir,
    "--iconBackgroundColor",
    icon.iconBackground,
    "--iconBackgroundColorDark",
    icon.iconBackgroundDark,
    "--splashBackgroundColor",
    mask.light,
    "--splashBackgroundColorDark",
    mask.dark,
    ...platforms.flatMap((p) => [`--${p}`]),
  ]
  await run(bin, args, { cwd: appRoot, report })
  return { warnings }
}

/** Build the static SPA for the Capacitor target and stamp its `index.html`. */
export async function buildWeb(appRoot, { report } = {}) {
  report?.("building SPA (NATIV_TARGET=capacitor)")
  const env = { ...process.env, NATIV_TARGET: "capacitor" }
  const vite = localBin(appRoot, "vite")
  if (vite) await run(vite, ["build"], { cwd: appRoot, env, report })
  else
    await run("npx", ["--yes", "vite", "build"], {
      cwd: appRoot,
      env,
      report,
    })

  const shell = path.join(appRoot, CAP_WEB_DIR, "_shell.html")
  const index = path.join(appRoot, CAP_WEB_DIR, "index.html")
  if (existsSync(shell)) copyFileSync(shell, index)
  else if (!existsSync(index)) {
    throw new Error(
      `SPA build produced no ${CAP_WEB_DIR}/_shell.html or index.html`,
    )
  }
}

/**
 * Scaffold the native project if it isn't there yet. Also migrates a legacy
 * app-root `ios/`/`android/` (pre-`.nativ/` layout) into `.nativ/` so existing
 * projects keep working after the relocation.
 */
export async function capAddIfMissing(
  appRoot,
  platform,
  env,
  { report } = {},
) {
  const dir = nativeDir(appRoot, platform)
  if (existsSync(dir)) return

  // one-time migration: an older layout scaffolded at the app root.
  const legacy = path.join(appRoot, platform)
  if (existsSync(legacy)) {
    mkdirSync(path.dirname(dir), { recursive: true })
    renameSync(legacy, dir)
    // Purge transient build caches — Xcode's DerivedData/ModuleCache and Gradle's
    // caches bake the project's ABSOLUTE path into precompiled modules, so a moved
    // project fails to build ("PCH was compiled with module cache path .../ios/...").
    // They're regenerated on the next build/sync; only the source needs to move.
    purgeBuildArtifacts(dir, platform)
    report?.(`migrated ./${platform} → ${NATIV_DIR}/${platform}`)
    return
  }

  let platformInstalled = false
  try {
    createRequire(path.join(appRoot, "package.json")).resolve(
      `@capacitor/${platform}/package.json`,
    )
    platformInstalled = true
  } catch {
    platformInstalled = false
  }
  if (!platformInstalled) {
    throw new Error(
      `@capacitor/${platform} is not installed. Add the native platform package:\n` +
        `    pnpm --filter <your-app> add @capacitor/${platform}`,
    )
  }
  report?.(`cap add ${platform} (first run — scaffolding native project)`)
  const { cmd, pre } = capCmd(appRoot)
  //iOS: force CocoaPods, never SPM (SPM's binary xcframework fails to compile the
  //plugin sources under Xcode 16; CocoaPods builds from source, BUILD SUCCEEDED).
  const pkgMgr =
    platform === "ios" ? ["--packagemanager", "CocoaPods"] : []
  await run(cmd, [...pre, "add", platform, ...pkgMgr], {
    cwd: appRoot,
    env,
    report,
  })
}

/** `cap sync <platform>` (copies web assets + updates native deps). */
export async function capSync(appRoot, platform, env, { report } = {}) {
  const { cmd, pre } = capCmd(appRoot)
  await run(cmd, [...pre, "sync", platform], { cwd: appRoot, env, report })
}

/** `cap run <platform> --target <id>` (build + install + launch). */
export async function capRun(
  appRoot,
  platform,
  target,
  env,
  { report } = {},
) {
  const { cmd, pre } = capCmd(appRoot)
  // Force a clean relaunch: kill any running instance first, so the WebView loads
  // FRESH from the (now-live) dev server. Without this a still-running app can be
  // re-fronted with its stale page intact — e.g. an iOS WebView left black because it
  // launched earlier with no server keeps showing black instead of reloading. `cap
  // run` reinstall + launch doesn't reliably force this, so nativ does it explicitly.
  terminateApp(appRoot, platform, target, env)
  const args = [...pre, "run", platform]
  if (target) args.push("--target", target)
  await run(cmd, args, { cwd: appRoot, env, report })
}

/**
 * adb serials of every connected device/emulator (state `device`). Used so adb calls
 * target a specific `-s <serial>`: with more than one emulator running, a bare `adb`
 * command is ambiguous and fails — which silently breaks `adb reverse` (→ the emulator
 * can't reach the host, → black screen).
 */
export function androidDevices(env) {
  const r = spawnSync("adb", ["devices"], { env, encoding: "utf8" })
  if (r.status !== 0 || !r.stdout) return []
  return r.stdout
    .split("\n")
    .slice(1)
    .map((l) => l.trim().split(/\s+/))
    .filter((p) => p.length >= 2 && p[1] === "device")
    .map((p) => p[0])
}

/**
 * The adb serial for the device `cap run --target <id>` means, or null if it can't be
 * pinned down.
 *
 * `--target` is an AVD NAME (e.g. `Pixel_10`), not a serial (`emulator-5554`), so any
 * per-device question has to be translated first. Getting this wrong is not academic:
 * checking "is the app installed" across ALL connected emulators means a second, idle
 * emulator that has never seen the app makes the answer `false` forever, and the run
 * cache can never hit. Returns null when ambiguous so callers fall back to the safe path.
 */
export function androidSerialForTarget(target, env) {
  const serials = androidDevices(env)
  if (serials.length === 0) return null
  if (serials.length === 1) return serials[0]
  if (!target) return null
  if (serials.includes(target)) return target // already a serial
  for (const s of serials) {
    const r = spawnSync("adb", ["-s", s, "emu", "avd", "name"], {
      env,
      encoding: "utf8",
    })
    const name = (r.stdout ?? "").split("\n")[0]?.trim()
    if (name && name === target) return s
  }
  return null
}

/**
 * Is the app ALREADY installed on the target device?
 *
 * The run cache can't be trusted on its own — it has no idea you wiped the simulator or
 * deleted the app from the launcher. This asks the device directly, which is cheap, and
 * is what makes "skip the build" safe rather than merely fast. Any doubt answers `false`
 * so the caller falls back to a full build; a wasted rebuild is free, a skipped one that
 * should have happened is a debugging nightmare.
 */
export function isAppInstalled(appRoot, platform, target, env) {
  const appId = readAppId(appRoot)
  if (!appId) return false
  if (platform === "ios") {
    if (!target) return false
    const r = spawnSync(
      "xcrun",
      ["simctl", "get_app_container", target, appId],
      { encoding: "utf8" },
    )
    return r.status === 0
  }
  if (platform === "android") {
    // Ask ONLY the device this run targets — see `androidSerialForTarget`.
    const serial = androidSerialForTarget(target, env)
    if (!serial) return false
    const r = spawnSync(
      "adb",
      ["-s", serial, "shell", "pm", "list", "packages", appId],
      { env, encoding: "utf8" },
    )
    return r.status === 0 && (r.stdout ?? "").includes(`package:${appId}`)
  }
  return false
}

/** Is the app currently RUNNING on the target device (not merely installed)? */
export function isAppRunning(appRoot, platform, target, env) {
  const appId = readAppId(appRoot)
  if (!appId) return false
  if (platform === "ios") {
    if (!target) return false
    const r = spawnSync(
      "xcrun",
      ["simctl", "spawn", target, "launchctl", "list"],
      { encoding: "utf8" },
    )
    return r.status === 0 && (r.stdout ?? "").includes(appId)
  }
  if (platform === "android") {
    const serial = androidSerialForTarget(target, env)
    if (!serial) return false
    const r = spawnSync("adb", ["-s", serial, "shell", "pidof", appId], {
      env,
      encoding: "utf8",
    })
    return r.status === 0 && (r.stdout ?? "").trim().length > 0
  }
  return false
}

/**
 * Launch an already-installed app WITHOUT building, syncing, or reinstalling.
 *
 * The fast path behind the run cache: in live-reload the binary is only a shell pointing
 * at the dev server, so when nothing native changed there is nothing to rebuild.
 *
 * Critically, an app that is ALREADY RUNNING is only brought to the front — never killed.
 * It has by then almost certainly reconnected on its own: the offline screen polls for
 * the dev server and navigates the moment it answers, so the user watches it go
 * "offline → live". Killing and relaunching on top of that produced a jarring second
 * reopen of an app that was already showing exactly what they wanted.
 *
 * (The old forced terminate existed to rescue a WebView left black by a launch with no
 * server. The offline screen + reconnect watchdog now cover that case, and `r` remains
 * the explicit escape hatch for a genuinely wedged app.)
 */
export function launchInstalledApp(appRoot, platform, target, env) {
  const appId = readAppId(appRoot)
  if (!appId) return false
  const running = isAppRunning(appRoot, platform, target, env)
  if (platform === "ios") {
    if (!target) return false
    // `simctl launch` on a running app activates it in place; only a stopped app needs
    // a clean start, and terminating one that isn't running is a no-op anyway.
    if (!running)
      spawnSync("xcrun", ["simctl", "terminate", target, appId])
    const r = spawnSync("xcrun", ["simctl", "launch", target, appId], {
      encoding: "utf8",
    })
    return r.status === 0
  }
  if (platform === "android") {
    const serial = androidSerialForTarget(target, env)
    if (!serial) return false
    // Same rule: the LAUNCHER intent alone re-fronts an existing task without
    // restarting it. force-stop ONLY when there's nothing live to preserve.
    if (!running) {
      spawnSync(
        "adb",
        ["-s", serial, "shell", "am", "force-stop", appId],
        {
          env,
        },
      )
    }
    const r = spawnSync(
      "adb",
      [
        "-s",
        serial,
        "shell",
        "monkey",
        "-p",
        appId,
        "-c",
        "android.intent.category.LAUNCHER",
        "1",
      ],
      { env, stdio: "ignore" },
    )
    return r.status === 0
  }
  return false
}

/** The app id from capacitor.config.json, or null if unreadable. */
function readAppId(appRoot) {
  try {
    return (
      JSON.parse(
        readFileSync(path.join(appRoot, "capacitor.config.json"), "utf8"),
      ).appId ?? null
    )
  } catch {
    return null
  }
}

/** Best-effort kill of the app so the next launch is a clean, fresh load. */
function terminateApp(appRoot, platform, target, env) {
  const appId = readAppId(appRoot)
  if (!appId) return
  if (platform === "ios" && target) {
    spawnSync("xcrun", ["simctl", "terminate", target, appId])
  } else if (platform === "android") {
    // target each device explicitly — a bare `adb shell` throws with >1 emulator.
    for (const s of androidDevices(env)) {
      spawnSync("adb", ["-s", s, "shell", "am", "force-stop", appId], {
        env,
      })
    }
  }
}

/**
 * Reload the Android app's WebView WITHOUT rebuilding — force-stop + relaunch on each
 * device. `cap run` resets the emulator's `adb reverse` while installing/launching, so
 * the app it just launched has no route to the dev server and shows a black WebView
 * with no JS to recover. After re-asserting the reverse, nativ relaunches the app so it
 * loads with a working route. (iOS shares the host loopback — nothing to do there.)
 */
export function relaunchAndroidApp(appRoot, env) {
  const appId = readAppId(appRoot)
  if (!appId) return
  for (const s of androidDevices(env)) {
    spawnSync("adb", ["-s", s, "shell", "am", "force-stop", appId], {
      env,
    })
    spawnSync(
      "adb",
      [
        "-s",
        s,
        "shell",
        "monkey",
        "-p",
        appId,
        "-c",
        "android.intent.category.LAUNCHER",
        "1",
      ],
      { env, stdio: "ignore" },
    )
  }
}

/* =============================================================================
 * toolchain env (unchanged behaviour; moved here)
 * ============================================================================= */

function firstExisting(paths) {
  return paths.find((p) => p && existsSync(p)) ?? null
}

/** ANDROID_HOME + a JDK for Gradle; explicit env wins. */
export function androidEnv() {
  const env = { ...process.env }
  env.ANDROID_HOME =
    env.ANDROID_HOME ??
    env.ANDROID_SDK_ROOT ??
    path.join(homedir(), "Library/Android/sdk")

  if (
    !env.JAVA_HOME ||
    !existsSync(path.join(env.JAVA_HOME, "bin/java"))
  ) {
    const jbr =
      "/Applications/Android Studio.app/Contents/jbr/Contents/Home"
    let javaHome = existsSync(path.join(jbr, "bin/java")) ? jbr : null
    if (!javaHome) {
      const r = spawnSync("/usr/libexec/java_home", [], {
        encoding: "utf8",
      })
      if (r.status === 0) javaHome = r.stdout.trim()
    }
    if (javaHome) env.JAVA_HOME = javaHome
  }
  if (
    !env.JAVA_HOME ||
    !existsSync(path.join(env.JAVA_HOME, "bin/java"))
  ) {
    throw new Error(
      "no JDK found. Install Android Studio (bundles one) or set JAVA_HOME.",
    )
  }
  env.PATH = `${path.join(env.ANDROID_HOME, "platform-tools")}:${env.PATH}`
  return env
}

/** LANG (CocoaPods on Ruby 3.4 needs UTF-8) + `pod` on PATH. */
export function iosEnv() {
  const env = { ...process.env, LANG: process.env.LANG ?? "en_US.UTF-8" }
  const onPath = spawnSync("sh", ["-c", "command -v pod"], { env })
  if (onPath.status !== 0) {
    const gemRoot = path.join(homedir(), ".gem/ruby")
    const gemBins = existsSync(gemRoot)
      ? readdirSync(gemRoot).map((v) => path.join(gemRoot, v, "bin"))
      : []
    const dir = firstExisting(
      [...gemBins, "/opt/homebrew/bin", "/usr/local/bin"].map((d) =>
        path.join(d, "pod"),
      ),
    )
    if (dir) env.PATH = `${path.dirname(dir)}:${env.PATH}`
  }
  return env
}

export function platformEnv(platform) {
  return platform === "ios" ? iosEnv() : androidEnv()
}
