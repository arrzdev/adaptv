// Declaring adaptv's plugins in the generated Android project — the injector itself, against a
// real directory, not just the merge helpers it calls.
//
// `native-state.test.mjs` covers the three merges in isolation and `resolvePluginPackages`
// covers the set they're given. Neither can catch the injector wiring them together wrong,
// which is the failure that shipped: the Android project declared exactly ONE plugin project
// (the only `@capacitor/*` the consumer app named itself) and adaptv's other twelve were never
// compiled in, so every native capability silently ran its web fallback.
//
// iOS has no equivalent test because `injectIosPluginPods` ends in `pod install` — running
// CocoaPods from a unit test is not a test, it's a build. Its plugin set comes from the same
// `resolvePluginPackages`, which is tested directly.
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { afterEach, describe, expect, it } from "vitest"
import { injectAndroidPluginProjects, nativeDir } from "./native.mjs"

// What `cap sync` writes on its own under pnpm: adaptv's plugins are adaptv's dependencies, so
// cap cannot discover a single one of them and the file arrives with only the core module.
const CAP_SETTINGS = `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
include ':capacitor-android'
project(':capacitor-android').projectDir = new File('../../../../../node_modules/@capacitor/android/capacitor')
`

const CAP_BUILD = `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
apply from: "../capacitor.settings.gradle"

android {
  compileOptions {
    sourceCompatibility JavaVersion.VERSION_21
    targetCompatibility JavaVersion.VERSION_21
  }
}

dependencies {

}
`

let appRoot = null
afterEach(() => {
  if (appRoot) rmSync(appRoot, { recursive: true, force: true })
  appRoot = null
})

/** A scratch app with the three files `cap sync` leaves behind, and nothing else. */
function scaffold() {
  appRoot = mkdtempSync(path.join(tmpdir(), "adaptv-plugins-"))
  writeFileSync(
    path.join(appRoot, "package.json"),
    JSON.stringify({ name: "scratch-app", dependencies: {} }),
  )
  const androidDir = nativeDir(appRoot, "android")
  mkdirSync(path.join(androidDir, "app"), { recursive: true })
  writeFileSync(
    path.join(androidDir, "capacitor.settings.gradle"),
    CAP_SETTINGS,
  )
  writeFileSync(
    path.join(androidDir, "app", "capacitor.build.gradle"),
    CAP_BUILD,
  )
  return androidDir
}

const read = (...p) => readFileSync(path.join(...p), "utf8")
const occurrences = (haystack, needle) => haystack.split(needle).length - 1

describe("injectAndroidPluginProjects — the twelve plugins cap could not find", () => {
  it("declares adaptv's own plugins in all three files, without being asked for any of them", () => {
    const androidDir = scaffold()
    injectAndroidPluginProjects(appRoot)

    const settings = read(androidDir, "capacitor.settings.gradle")
    const build = read(androidDir, "app", "capacitor.build.gradle")
    const registry = JSON.parse(
      read(androidDir, "app/src/main/assets/capacitor.plugins.json"),
    )

    //haptics is the canonical one: `Haptics.impact()` rejects with "not implemented on
    //android" when any of the three files misses it, and each file misses it differently
    expect(settings).toContain("include ':capacitor-haptics'")
    expect(build).toContain("implementation project(':capacitor-haptics')")
    expect(registry).toContainEqual({
      pkg: "@capacitor/haptics",
      classpath: "com.capacitorjs.plugins.haptics.HapticsPlugin",
    })
    //cap's own module survives the merge — it is the app's dependency on the bridge itself
    expect(settings).toContain("include ':capacitor-android'")
  })

  it("declares a plugin the app ALSO lists exactly once (two `implementation project(...)` lines for one module fails the Gradle build)", () => {
    const androidDir = scaffold()
    injectAndroidPluginProjects(appRoot, {
      plugins: ["@capacitor/device"],
    })

    const settings = read(androidDir, "capacitor.settings.gradle")
    const build = read(androidDir, "app", "capacitor.build.gradle")
    const registry = JSON.parse(
      read(androidDir, "app/src/main/assets/capacitor.plugins.json"),
    )

    expect(occurrences(settings, "include ':capacitor-device'")).toBe(1)
    expect(
      occurrences(build, "implementation project(':capacitor-device')"),
    ).toBe(1)
    expect(
      registry.filter(
        (e) =>
          e.classpath === "com.capacitorjs.plugins.device.DevicePlugin",
      ),
    ).toHaveLength(1)
  })

  //This injector used to STATE the missing plugin — first onto `report()`, where `prettyLine`
  //erased every character of it, then onto a `warnings` channel. Neither was its business:
  //whether a name in `plugins` resolves is knowable from the dev's own files with no native
  //project in sight, so it is `preflight`'s `✖` now and the run ends before this code is
  //reached (R33). Its remaining job is not to CRASH on the name, and to declare the rest —
  //this injector also runs from `capSync` inside a lane, where a throw would take a build
  //down over a fact already refused above it. The sentence is asserted in `preflight.test.mjs`.
  it("skips a plugin that isn't installed, silently, and declares the rest anyway", () => {
    const androidDir = scaffold()
    const said = []
    injectAndroidPluginProjects(appRoot, {
      report: (line) => said.push(line),
      plugins: ["@capacitor/not-a-real-plugin"],
    })

    //Nothing about it on the live row, and nowhere else either — one fact, said once, and
    //said by preflight (R18).
    expect(said.filter((l) => l.includes("not-a-real-plugin"))).toEqual([])
    expect(read(androidDir, "capacitor.settings.gradle")).toContain(
      "include ':capacitor-haptics'",
    )
  })

  it("is idempotent — `cap sync` rewrites all three files, so this runs after every one of them", () => {
    const androidDir = scaffold()
    const files = [
      path.join(androidDir, "capacitor.settings.gradle"),
      path.join(androidDir, "app", "capacitor.build.gradle"),
      path.join(androidDir, "app/src/main/assets/capacitor.plugins.json"),
    ]
    injectAndroidPluginProjects(appRoot, {
      plugins: ["@capacitor/device"],
    })
    const once = files.map((f) => readFileSync(f, "utf8"))
    injectAndroidPluginProjects(appRoot, {
      plugins: ["@capacitor/device"],
    })
    expect(files.map((f) => readFileSync(f, "utf8"))).toEqual(once)
  })

  it("does nothing at all when there is no generated project to declare into", () => {
    appRoot = mkdtempSync(path.join(tmpdir(), "adaptv-plugins-"))
    const said = []
    injectAndroidPluginProjects(appRoot, {
      report: (line) => said.push(line),
    })
    expect(existsSync(nativeDir(appRoot, "android"))).toBe(false)
    expect(said).toEqual([])
  })
})
